import assert from 'node:assert/strict';
import {amount,initialPrice,autoSettlement,calculate,totals,ligaLink} from '../calculator.js';
assert.equal(amount('1,25'),1.25);assert.equal(amount(-10),null);assert.equal(amount('Infinity'),null);
assert.equal(initialPrice({historical_quote:'1.51 / 5.00 / 6.00'}),null);
assert.equal(initialPrice({historical_quote:'≈2.16'}),2.16);
assert.equal(autoSettlement({market:'П1',reported_forecast_result:'✅ Сбылся'}),'pending');
assert.equal(autoSettlement({market:'П1',forecast_result:'✅ Сбылся'}),'won');
const base={stake:100,odds:2.5,settlement:'won'};
assert.deepEqual(calculate(base),{stake:100,odds:2.5,potential:250,payout:250,profit:150});
assert.equal(calculate({...base,settlement:'lost'}).profit,-100);
assert.equal(calculate({...base,settlement:'refund'}).profit,0);
assert.equal(calculate({...base,settlement:'pending'}).payout,null);
assert.equal(calculate({...base,odds:'',settlement:'won'}).payout,null);
const t=totals([base,{...base,settlement:'lost'},{...base,settlement:'pending'}],1000);
assert.equal(t.staked,300);assert.equal(t.profit,50);assert.equal(t.available,950);assert.equal(t.balance,1050);assert.equal(t.pending,100);assert.equal(t.weighted,2.5);
assert.equal(totals([{...base,odds:''}],1000).potential,null);
assert.equal(totals([base],'').balance,null);
assert.equal(ligaLink({event:'Лада — СКА',calendar_date:'15.10.2026'}),'https://www.ligastavok.ru/sports/ice-hockey/lada-ska-id-23754569-service-id-26-ext-id-1164481');
assert.equal(ligaLink({event:'Лада — СКА',event_date:'2025-10-15'}),null);
assert.equal(ligaLink({source_url:'https://ligastavok.ru.evil.example/sports/lada-id-123'}),null);
console.log('Calculator passed: payouts, losses, refunds, pending entries, bankroll, ambiguous odds and event links.');
